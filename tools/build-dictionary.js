/* Builds assist-dictionary.js (offline spelling data).
   Usage: npm i word-list popular-english-words && node tools/build-dictionary.js
   - word-list (MIT, Sindre Sorhus): ~274k valid English words incl. UK + US spellings -> Bloom filter
   - popular-english-words (ISC, Tim Koop): frequency ranking -> top common words used to rank suggestions */
const fs = require("fs");
const path = require("path");
const R = m => path.join(process.cwd(), "node_modules", m);
const wl = R("word-list/words.txt");
const words = fs.readFileSync(wl, "utf8").split("\n").filter(w => /^[a-z]{2,}$/.test(w));
const valid = new Set(words);

const pop = fs.readFileSync(R("popular-english-words/words.js"), "utf8");
const list = new Function(pop.slice(pop.indexOf("["), pop.lastIndexOf("]") + 1).replace(/^/, "return "))();
const TOP = 20000;
const top = [], seen = new Set();
for (const w of list) { if (valid.has(w) && !seen.has(w)) { seen.add(w); top.push(w); } if (top.length >= TOP) break; }

/* Bloom filter: must match the hashing in assist-spell.js */
const BITS_PER_WORD = 9, K = 6;
const m = Math.ceil(words.length * BITS_PER_WORD);
const bits = new Uint8Array(Math.ceil(m / 8));
function hashes(w) {
  let h1 = 2166136261, h2 = 5381;
  for (let i = 0; i < w.length; i++) { const c = w.charCodeAt(i); h1 = Math.imul(h1 ^ c, 16777619) >>> 0; h2 = (Math.imul(h2, 33) + c) >>> 0; }
  return [h1, h2 | 1];
}
for (const w of words) {
  const [a, b] = hashes(w);
  for (let i = 0; i < K; i++) { const p = (a + Math.imul(i, b)) >>> 0; const bit = p % m; bits[bit >> 3] |= 1 << (bit & 7); }
}
const out = "/* Generated by tools/build-dictionary.js. Do not edit.\n   Bloom filter over " + words.length + " English words (UK+US) and " + top.length + " common words ranked by frequency. */\n" +
  "window.MirrorFlowDictionary = " + JSON.stringify({ m, k: K, count: words.length, bloom: Buffer.from(bits).toString("base64"), top: top.join(" ") }) + ";\n";
fs.writeFileSync(path.join(__dirname, "..", "assist-dictionary.js"), out);
console.log("words", words.length, "top", top.length, "bloom bytes", bits.length, "file bytes", out.length);
